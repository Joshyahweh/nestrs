//! `create_dto`: write a `#[derive(...)] struct` with the user's fields
//! and validators.

use std::fs;
use std::path::Path;

use schemars::JsonSchema;
use serde::{Deserialize, Serialize};

use crate::Result;

use super::ScaffoldReport;

#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema)]
pub struct DtoFieldSpec {
    pub name: String,
    pub ty: String,
    #[serde(default)]
    pub optional: bool,
    #[serde(default)]
    pub validators: Vec<String>,
}

pub fn create_dto(path: &Path, name: &str, fields: &[DtoFieldSpec]) -> Result<ScaffoldReport> {
    if !is_safe_ident(name) {
        return Err(crate::Error::InvalidArgument(format!(
            "DTO name `{name}` is not a valid Rust ident"
        )));
    }
    for field in fields {
        if !is_safe_ident(&field.name) {
            return Err(crate::Error::InvalidArgument(format!(
                "DTO field `{}` is not a valid Rust ident",
                field.name
            )));
        }
        if !is_safe_rust_type(&field.ty) {
            return Err(crate::Error::InvalidArgument(format!(
                "DTO field type `{}` is not a plain Rust type",
                field.ty
            )));
        }
        for validator in &field.validators {
            if !is_safe_attribute(validator) {
                return Err(crate::Error::InvalidArgument(format!(
                    "DTO validator `{validator}` is not a single Rust attribute"
                )));
            }
        }
    }
    let mut report = ScaffoldReport::new();
    let content = render_dto(name, fields);
    let out_path = path.join("src").join(format!("{}.rs", snake_case(name)));
    fs::create_dir_all(out_path.parent().unwrap())?;
    fs::write(&out_path, content)?;
    report.created(out_path.to_string_lossy());
    Ok(report)
}

fn render_dto(name: &str, fields: &[DtoFieldSpec]) -> String {
    let mut s = String::new();
    s.push_str("//! DTO generated by `nestrs-mcp`.\n\n");
    s.push_str(
        "use nestrs::dto;\nuse serde::{Deserialize, Serialize};\nuse validator::Validate;\n\n",
    );
    s.push_str("#[derive(Debug, Clone, Serialize, Deserialize, Validate, Default)]\n");
    s.push_str("#[dto(allow_unknown_fields)]\n");
    s.push_str(&format!("pub struct {name} {{\n"));
    for f in fields {
        let opt = if f.optional { "Option<" } else { "" };
        let close = if f.optional { ">" } else { "" };
        s.push_str("    #[serde(default)]\n");
        for v in &f.validators {
            s.push_str(&format!("    {v}\n"));
        }
        s.push_str(&format!("    pub {}: {}{}{},\n", f.name, opt, f.ty, close));
    }
    s.push_str("}\n");
    s
}

fn is_safe_ident(s: &str) -> bool {
    !s.is_empty()
        && s.len() <= 64
        && s.chars()
            .next()
            .is_some_and(|c| c.is_ascii_alphabetic() || c == '_')
        && s.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
}

/// Type position only: idents, paths, references, generics. No quotes,
/// comments, or statement breaks, so a field type cannot close the struct.
fn is_safe_rust_type(ty: &str) -> bool {
    !ty.is_empty()
        && ty.len() <= 128
        && !ty.contains("--")
        && ty.chars().all(|c| {
            c.is_ascii_alphanumeric()
                || matches!(
                    c,
                    '_' | ':' | '<' | '>' | ',' | ' ' | '&' | '\'' | '[' | ']'
                )
        })
}

/// One attribute token (`#[validate(email)]`). Newlines and braces would
/// let the string insert further items into the generated module.
fn is_safe_attribute(attr: &str) -> bool {
    attr.len() <= 256
        && attr.starts_with("#[")
        && attr.ends_with(']')
        && !attr.contains('\n')
        && !attr.contains('\r')
        && attr.chars().all(|c| {
            c.is_ascii_alphanumeric()
                || matches!(
                    c,
                    '_' | ':'
                        | ','
                        | '='
                        | '('
                        | ')'
                        | ' '
                        | '"'
                        | '\''
                        | '.'
                        | '<'
                        | '>'
                        | '-'
                        | '#'
                        | '['
                        | ']'
                )
        })
}

fn snake_case(s: &str) -> String {
    let mut out = String::new();
    for (i, c) in s.chars().enumerate() {
        if c.is_ascii_uppercase() {
            if i > 0 {
                out.push('_');
            }
            out.push(c.to_ascii_lowercase());
        } else {
            out.push(c);
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn field(name: &str, ty: &str, validators: &[&str]) -> DtoFieldSpec {
        DtoFieldSpec {
            name: name.into(),
            ty: ty.into(),
            optional: false,
            validators: validators.iter().map(|v| (*v).to_string()).collect(),
        }
    }

    #[test]
    fn create_dto_writes_a_plain_field() {
        let dir = std::env::temp_dir().join(format!(
            "nestrs-mcp-dto-ok-{}-{}",
            std::process::id(),
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .unwrap()
                .as_nanos()
        ));
        let _ = fs::remove_dir_all(&dir);
        create_dto(
            &dir,
            "UserDto",
            &[field("email", "String", &["#[validate(email)]"])],
        )
        .expect("safe dto");
        let text = fs::read_to_string(dir.join("src/user_dto.rs")).unwrap();
        assert!(text.contains("pub email: String"));
        assert!(text.contains("#[validate(email)]"));
        let _ = fs::remove_dir_all(&dir);
    }

    #[test]
    fn create_dto_rejects_type_and_validator_injection_before_writing() {
        let dir = std::env::temp_dir().join(format!(
            "nestrs-mcp-dto-bad-{}-{}",
            std::process::id(),
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .unwrap()
                .as_nanos()
        ));
        let _ = fs::remove_dir_all(&dir);
        let type_err = create_dto(
            &dir,
            "User",
            &[field(
                "name",
                "String; std::process::exit(0); pub x: u8",
                &[],
            )],
        )
        .unwrap_err();
        assert!(type_err.to_string().contains("not a plain Rust type"));
        let attr_err = create_dto(
            &dir,
            "User",
            &[field(
                "name",
                "String",
                &["#[validate(email)]\npub pwned: String,"],
            )],
        )
        .unwrap_err();
        assert!(attr_err.to_string().contains("not a single Rust attribute"));
        assert!(
            !dir.join("src").exists(),
            "rejected scaffold must not write files"
        );
    }
}
